// Diagram layout: turns diagrams/<name>.json (what to draw) into diagrams/<name>.html (where to draw it).
// Usage: node <kit>/tools/diagram_layout.mjs <deck folder>   (build.mjs runs it before the diagrams step)
//
// Every position is computed here, in whole pixels, on a grid: equal column widths and gaps, a grid
// centered in the diagram, handoff badges centered in their slice and in the band between two lanes, so
// the line above a handoff is exactly as long as the line below it. Nothing is placed by eye.
// Each element carries a data-role (slice, label, lane-label, box, handoff, segment, step, arrow), which
// the geometry check in diagrams.mjs measures. The generated HTML says so at the top: edit the JSON.
//
// Two types:
//   lanes  a wide, short band: full-width lanes labeled on the left, crossed by columns (slices) titled on
//          top; in each slice one handoff pill sits centered on each lane boundary, with an arrow down.
//          Spec: { type, width, aspect (default 2.4), colors, fonts, lanes:[{label,sub}], columns:[...],
//          handoff:"HANDOFF", emphasis:{column}, laneLabelWidth }
//   flow   steps in a row joined by arrows, with an optional loop back from the last step to the first.
//          Spec: { type, width, colors, fonts, steps:[...], loop:"label", emphasis:{step} }
// colors: background, panel, box, border, line, text, muted, accent, accentText. fonts: text, mono.
import fs from 'fs';
import path from 'path';

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const even = (n) => n - (n % 2);
const box = (role, x, y, w, h, css, inner = '', extra = '') =>
  `<div data-role="${role}"${extra} style="position:absolute;left:${x}px;top:${y}px;width:${w}px;height:${h}px;${css}">${inner}</div>`;

function need(spec, keys, where) {
  const missing = keys.filter((k) => spec[k] === undefined || spec[k] === null || spec[k] === '');
  if (missing.length) throw new Error(`${where}: missing ${missing.join(', ')}`);
}

function page(spec, w, h, body) {
  const c = spec.colors;
  return `<!doctype html>
<!-- Generated by tools/diagram_layout.mjs from this diagram's .json spec. Don't edit this file: edit the .json and build again. -->
<html><head><meta charset="utf-8"><link rel="stylesheet" href="../fonts/fonts.css"><style>
body{margin:0}
.diagram{position:relative;width:${w}px;height:${h}px;background:${c.background};font-family:'${spec.fonts.text}';color:${c.text}}
.diagram div{box-sizing:border-box}
.t{display:flex;align-items:center;justify-content:center;text-align:center;line-height:1.25}
</style></head><body>
<div class="diagram" style="width:${w}px;height:${h}px">
${body.join('\n')}
</div></body></html>
`;
}

// lanes: a wide, short band. Each lane is one full-width band, labeled on the left. The slices are
// outlined columns that cross every band, titled on top. In each slice, one handoff pill sits centered
// on each boundary between two lanes, with a line from the middle of the lane above to the pill and an
// equal line from the pill to the middle of the lane below, ending in an arrow. The height comes from the
// width and the aspect ratio (width / height, default 2.4), so the diagram stays a band.
function lanes(spec) {
  need(spec, ['width', 'colors', 'fonts', 'lanes', 'columns'], 'lanes spec');
  if (spec.cells) throw new Error('lanes spec: "cells" is no longer used. Say what each lane does in lanes[].sub; the slices are titled by "columns".');
  const c = spec.colors;
  const L = spec.lanes.length, N = spec.columns.length;
  if (L < 2 || N < 1) throw new Error('lanes spec: needs at least 2 lanes and 1 column');
  spec.lanes.forEach((ln, i) => { if (!String(ln.label || '').trim()) throw new Error(`lanes spec: lanes[${i}].label is empty; every lane needs a label`); });
  spec.columns.forEach((t, j) => { if (!String(t || '').trim()) throw new Error(`lanes spec: columns[${j}] is empty; every slice needs a title`); });

  const aspect = spec.aspect || 2.4;
  if (aspect < 2 || aspect > 3.2) throw new Error(`lanes spec: aspect ${aspect} is outside 2 to 3.2; a lane diagram is a wide, short band (about 2.4)`);
  const W = spec.width, H = even(Math.round(W / aspect));
  const pad = 24, gap = 24, laneW = spec.laneLabelWidth || 280, laneGap = 8, headerH = 56, badgeH = 48;
  const laneTop = pad + headerH;
  const laneH = even(Math.floor((H - pad - 8 - laneTop - (L - 1) * laneGap) / L));
  if (laneH < 120) throw new Error(`lanes spec: each lane would be ${laneH}px tall (need 120). Make the diagram wider, or lower "aspect".`);
  const laneY = (i) => laneTop + i * (laneH + laneGap);
  const sliceBot = laneY(L - 1) + laneH + 8;                      // the slice outline runs 8 px past the last lane
  const H2 = sliceBot + pad;                                      // within a few px of W / aspect after rounding
  const sx0 = pad + laneW + gap;                                  // the slices start right of the lane labels
  const avail = W - pad - 16 - sx0 - (N - 1) * gap;               // 16 px of band shows right of the last slice
  const colW = even(Math.floor(avail / N));                       // even, so the center is a whole pixel
  const x0 = sx0 + Math.floor((avail - colW * N) / 2);
  if (colW < 160) throw new Error(`lanes spec: each slice would be ${colW}px wide (need 160). Make the diagram wider or the lane labels narrower.`);
  const badgeW = even(Math.min(colW - 32, spec.handoffWidth || 200));
  const out = [];
  const emph = spec.emphasis && Number.isInteger(spec.emphasis.column) ? spec.emphasis.column : -1;

  spec.lanes.forEach((ln, i) => {
    out.push(box('lane', pad, laneY(i), W - 2 * pad, laneH, `background:${c.panel};border:2px solid ${c.border};border-radius:8px`, '', ` data-lane="${i}"`));
    out.push(box('lane-label', pad + 2, laneY(i) + 2, laneW - 2, laneH - 4, `padding:12px 24px;display:flex;flex-direction:column;justify-content:center;gap:8px`,
      `<div style="font:700 24px '${spec.fonts.mono}';color:${c.accent};line-height:1.25">${esc(ln.label)}</div>` +
      (ln.sub ? `<div style="font:700 24px '${spec.fonts.text}';color:${c.text};line-height:1.25">${esc(ln.sub)}</div>` : ''), ` data-lane="${i}"`));
  });
  spec.columns.forEach((name, j) => {
    const x = x0 + j * (colW + gap);
    const cx = x + colW / 2;
    const hot = j === emph;
    out.push(box('slice', x, pad, colW, sliceBot - pad, `border:2px solid ${hot ? c.accent : c.line};border-radius:8px`, '', ` data-col="${j}"`));
    out.push(box('label', x, pad, colW, headerH, `font:700 28px '${spec.fonts.text}';color:${c.text}`, esc(name), ` data-col="${j}" class="t"`));
    for (let i = 0; i < L - 1; i++) {
      const boundary = laneY(i) + laneH + laneGap / 2;              // the line between lane i and lane i+1
      const by = boundary - badgeH / 2;                             // the pill is centered on it
      const top = laneY(i) + laneH / 2, bot = laneY(i + 1) + laneH / 2;
      const seg = by - top;                                         // = bot - (by + badgeH): equal by symmetry
      out.push(box('segment', cx - 1, top, 2, seg, `background:${c.line}`, '', ` data-col="${j}" data-pos="above"`));
      out.push(box('segment', cx - 1, by + badgeH, 2, seg, `background:${c.line}`, '', ` data-col="${j}" data-pos="below"`));
      out.push(box('arrow', cx - 8, bot - 10, 16, 10, `width:0;height:0;border-left:8px solid transparent;border-right:8px solid transparent;border-top:10px solid ${c.line}`, '', ` data-col="${j}"`));
      out.push(box('handoff', cx - badgeW / 2, by, badgeW, badgeH, `background:${c.accent};border-radius:24px;font:700 24px '${spec.fonts.mono}';color:${c.accentText};letter-spacing:1px`,
        esc(spec.handoff || 'HANDOFF'), ` data-col="${j}" class="t"`));
    }
  });
  return page(spec, W, H2, out);
}

function flow(spec) {
  need(spec, ['width', 'colors', 'fonts', 'steps'], 'flow spec');
  const c = spec.colors;
  const N = spec.steps.length;
  if (N < 2) throw new Error('flow spec: needs at least 2 steps');
  spec.steps.forEach((t, j) => { if (!String(t || '').trim()) throw new Error(`flow spec: steps[${j}] is empty; every box needs a label`); });
  const W = spec.width, pad = 24, arrowGap = 56, boxH = 96;
  const avail = W - 2 * pad - (N - 1) * arrowGap;
  const stepW = even(Math.floor(avail / N));
  const x0 = pad + Math.floor((avail - stepW * N) / 2);
  const loopH = spec.loop ? 120 : 0;
  const H = pad + boxH + loopH + pad;
  const y = pad, cy = y + boxH / 2;
  const emph = spec.emphasis && Number.isInteger(spec.emphasis.step) ? spec.emphasis.step : -1;
  const out = [];
  for (let j = 0; j < N; j++) {
    const x = x0 + j * (stepW + arrowGap);
    const hot = j === emph;
    out.push(box('step', x, y, stepW, boxH, `background:${hot ? c.accent : c.box};border:2px solid ${hot ? c.accent : c.border};border-radius:8px;padding:8px 12px;font:700 24px '${spec.fonts.text}';color:${hot ? c.accentText : c.text}`,
      esc(spec.steps[j]), ` data-step="${j}" class="t"`));
    if (j < N - 1) {
      const ax = x + stepW + 8, aw = arrowGap - 16;
      out.push(box('segment', ax, cy - 1, aw - 10, 2, `background:${c.line}`, '', ` data-step="${j}"`));
      out.push(box('arrow', ax + aw - 10, cy - 8, 10, 16, `width:0;height:0;border-top:8px solid transparent;border-bottom:8px solid transparent;border-left:10px solid ${c.line}`, '', ` data-step="${j}"`));
    }
  }
  if (spec.loop) {
    const first = x0 + stepW / 2, last = x0 + (N - 1) * (stepW + arrowGap) + stepW / 2;
    const top = y + boxH + 8, lineY = y + boxH + 64;
    out.push(box('segment', last - 1, top, 2, lineY - top, `background:${c.line}`, '', ' data-pos="loop-down"'));
    out.push(box('segment', first, lineY - 1, last - first, 2, `background:${c.line}`, '', ' data-pos="loop-back"'));
    out.push(box('segment', first - 1, top + 10, 2, lineY - top - 10, `background:${c.line}`, '', ' data-pos="loop-up"'));
    out.push(box('arrow', first - 8, top, 16, 10, `width:0;height:0;border-left:8px solid transparent;border-right:8px solid transparent;border-bottom:10px solid ${c.line}`));
    const lw = even(Math.min(last - first - 48, 640));
    out.push(box('label', (first + last) / 2 - lw / 2, lineY + 8, lw, 40, `font:400 24px '${spec.fonts.text}';color:${c.muted}`, esc(spec.loop), ' class="t"'));
  }
  return page(spec, W, H, out);
}

// --- main
const deck = path.resolve(process.argv[2] || '.');
const dir = path.join(deck, 'diagrams');
const specs = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort() : [];
if (!specs.length) { console.log('No diagrams/*.json: nothing to lay out.'); process.exit(0); }
let bad = 0;
for (const f of specs) {
  const name = f.replace(/\.json$/, '');
  try {
    const spec = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
    spec.fonts = spec.fonts || {};
    if (!spec.fonts.text || !spec.fonts.mono) throw new Error('fonts.text and fonts.mono are required (from design.md)');
    const COLOR_KEYS = ['background', 'panel', 'box', 'border', 'line', 'text', 'muted', 'accent', 'accentText'];
    const badColors = COLOR_KEYS.filter((k) => !/^#[0-9a-f]{3}([0-9a-f]{3})?$/i.test(String((spec.colors || {})[k] || '')));
    if (badColors.length) throw new Error(`colors needs a hex value for: ${badColors.join(', ')} (diagram-specs.md lists which design token goes in each)`);
    const html = spec.type === 'lanes' ? lanes(spec) : spec.type === 'flow' ? flow(spec) : (() => { throw new Error(`unknown type "${spec.type}" (use lanes or flow)`); })();
    fs.writeFileSync(path.join(dir, `${name}.html`), html);
    console.log(`Diagram layout ${name}: ${spec.type} -> diagrams/${name}.html`);
  } catch (e) {
    console.log(`PROBLEM  diagram layout ${name}: ${e.message}`);
    bad++;
  }
}
process.exit(bad ? 1 : 0);
